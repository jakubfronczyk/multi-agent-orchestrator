//! Tool types the engine reads: the 13 names, each tool's fixed spec and the action it describes.
//! Policy reads only `ToolSpec`; tool code lives in the server behind the `Tool` trait.

use std::time::Duration;

use schemars::JsonSchema;
use schemars::generate::SchemaSettings;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use ts_rs::TS;

use crate::agents::{Slug, ValidationError};
use crate::policy::{Effect, LeadAccess};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum ToolName {
    Delegate,
    Plan,
    MemoryRead,
    MemorySearch,
    MemoryWrite,
    FileList,
    FileRead,
    FileWrite,
    InboxList,
    InboxRead,
    HttpFetch,
    CsvQuery,
    SendMessage,
}

/// Everything the engine knows about a tool; the only contact between tools and policy.
#[derive(Debug, Clone)]
pub struct ToolSpec {
    pub name: ToolName,
    pub description: String,
    /// The JSON schema the model is shown, generated by `schema_for`.
    pub schema: Value,
    pub effect: Effect,
    pub taints: bool,
    pub lead: LeadAccess,
    pub timeout: Option<Duration>,
}

/// Generates a tool's argument schema with fixed settings: draft 2020-12, every
/// subschema inlined, no `$schema` key.
pub fn schema_for<T: JsonSchema>() -> Value {
    let mut settings = SchemaSettings::draft2020_12();
    settings.inline_subschemas = true;
    settings.meta_schema = None;
    settings
        .into_generator()
        .into_root_schema_for::<T>()
        .to_value()
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum MemoryScope {
    Private,
    Shared,
}

/// A memory note's key: `[a-z0-9_./-]{1,128}`.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(try_from = "String")]
#[ts(export, type = "string")]
pub struct NoteKey(String);

impl NoteKey {
    pub fn new(value: &str) -> Result<Self, ValidationError> {
        let valid_char = |c: char| {
            c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, '_' | '.' | '/' | '-')
        };
        if value.is_empty() || value.len() > 128 || !value.chars().all(valid_char) {
            return Err(ValidationError::new(
                "key",
                "use 1 to 128 of a-z, 0-9, _ . / and -",
            ));
        }
        Ok(Self(value.to_string()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl TryFrom<String> for NoteKey {
    type Error = ValidationError;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        NoteKey::new(&value)
    }
}

/// One step of the Lead's plan; `agent` is a slug or "self".
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct PlanStep {
    pub agent: String,
    pub goal: String,
}

/// What a call would do, for the card and custody.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct Action {
    pub verb: String,
    pub target: Target,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
#[ts(export)]
pub enum Target {
    File { path: String },
    Recipient { channel: String, address: String },
    Host { url: String, host: String },
    Note { scope: MemoryScope, key: NoteKey },
    Query { text: String },
    Agent { slug: Slug },
    Plan { steps: Vec<PlanStep> },
}
