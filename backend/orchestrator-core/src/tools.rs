//! Tool types the engine reads: the 13 names, each tool's fixed `ToolSpec` and its `Action`.
//! Policy reads only `ToolSpec`; tool code lives in the server behind the `Tool` trait.

use std::sync::Arc;
use std::time::Duration;

use async_trait::async_trait;
use schemars::JsonSchema;
use schemars::generate::SchemaSettings;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use ts_rs::TS;

use crate::agents::{Slug, ValidationError};
use crate::ids::{AgentId, RunId};
use crate::policy::{Effect, LeadAccess, TaintSource, Trust};

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum ToolName {
    Delegate,
    Plan,
    MemoryRead,
    MemorySearch,
    MemoryWrite,
    FileList,
    FileRead,
    FileWrite,
    InboxList,
    InboxRead,
    HttpFetch,
    CsvQuery,
    SendMessage,
}

/// The fixed risk table: effect, taint and Lead access depend only on which tool it is.
/// Every match lists all 13 tools, so a new tool fails to compile until it is placed.
impl ToolName {
    pub fn effect(self) -> Effect {
        match self {
            ToolName::Delegate | ToolName::Plan => Effect::Control,
            ToolName::MemoryRead
            | ToolName::MemorySearch
            | ToolName::FileList
            | ToolName::FileRead
            | ToolName::InboxList
            | ToolName::InboxRead
            | ToolName::CsvQuery => Effect::Read,
            ToolName::MemoryWrite => Effect::Memory,
            ToolName::FileWrite => Effect::Write,
            ToolName::HttpFetch => Effect::Egress,
            ToolName::SendMessage => Effect::External,
        }
    }

    pub fn taints(self) -> bool {
        match self {
            ToolName::InboxList | ToolName::InboxRead | ToolName::HttpFetch => true,
            ToolName::Delegate
            | ToolName::Plan
            | ToolName::MemoryRead
            | ToolName::MemorySearch
            | ToolName::MemoryWrite
            | ToolName::FileList
            | ToolName::FileRead
            | ToolName::FileWrite
            | ToolName::CsvQuery
            | ToolName::SendMessage => false,
        }
    }

    pub fn lead(self) -> LeadAccess {
        match self {
            ToolName::Delegate | ToolName::Plan => LeadAccess::Only,
            ToolName::MemoryRead | ToolName::MemorySearch | ToolName::MemoryWrite => {
                LeadAccess::Allowed
            }
            ToolName::FileList
            | ToolName::FileRead
            | ToolName::FileWrite
            | ToolName::InboxList
            | ToolName::InboxRead
            | ToolName::HttpFetch
            | ToolName::CsvQuery
            | ToolName::SendMessage => LeadAccess::Forbidden,
        }
    }
}

/// What the model is shown about a tool. Risk is not stored here; it comes from `ToolName`.
#[derive(Debug, Clone)]
pub struct ToolSpec {
    pub name: ToolName,
    pub description: String,
    /// Generated by `schema_for`.
    pub schema: Value,
    pub timeout: Option<Duration>,
}

/// Every tool description ends with this line.
pub const MAY_ASK: &str = "May need human approval. If refused, do not retry; report it.";

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum ToolError {
    /// The arguments do not fit the tool; the message names the field.
    #[error("{0}")]
    InvalidArgs(String),
    #[error("{0}")]
    Failed(String),
}

/// What a running tool knows about its caller. Owned, so a spawned tool needs no borrow.
#[derive(Debug, Clone)]
pub struct ToolCtx {
    pub run_id: RunId,
    pub root_run_id: RunId,
    pub agent_id: AgentId,
    pub trust: Trust,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ToolOutput {
    pub content: Value,
    /// The outside content this result carries; read only when the tool's name taints.
    pub taint: Vec<TaintSource>,
}

#[async_trait]
pub trait Tool: Send + Sync {
    fn spec(&self) -> &ToolSpec;
    /// Parses and validates the arguments without I/O, describing what the call would do.
    fn check(&self, args: &Value) -> Result<Action, ToolError>;
    async fn run(&self, ctx: &ToolCtx, args: Value) -> Result<ToolOutput, ToolError>;

    /// What the approval card shows: the arguments, unless the tool renders something clearer.
    async fn preview(&self, args: &Value) -> String {
        serde_json::to_string_pretty(args).unwrap_or_default()
    }
}

pub struct ToolSet {
    tools: Vec<Arc<dyn Tool>>,
}

impl ToolSet {
    pub fn new(tools: Vec<Arc<dyn Tool>>) -> Self {
        Self { tools }
    }

    pub fn get(&self, name: ToolName) -> Option<Arc<dyn Tool>> {
        self.tools
            .iter()
            .find(|tool| tool.spec().name == name)
            .cloned()
    }
}

/// Generates a tool's argument schema with fixed settings: draft 2020-12, every
/// subschema inlined, no `$schema` key.
pub fn schema_for<T: JsonSchema>() -> Value {
    let mut settings = SchemaSettings::draft2020_12();
    settings.inline_subschemas = true;
    settings.meta_schema = None;
    settings
        .into_generator()
        .into_root_schema_for::<T>()
        .to_value()
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS, JsonSchema)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum MemoryScope {
    Private,
    Shared,
}

/// A memory note's key: `[a-z0-9_./-]{1,128}`.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize, TS, JsonSchema)]
#[serde(try_from = "String")]
#[ts(export, type = "string")]
pub struct NoteKey(String);

impl NoteKey {
    pub fn new(value: &str) -> Result<Self, ValidationError> {
        let valid_char = |c: char| {
            c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, '_' | '.' | '/' | '-')
        };
        if value.is_empty() || value.len() > 128 || !value.chars().all(valid_char) {
            return Err(ValidationError::new(
                "key",
                "use 1 to 128 of a-z, 0-9, _ . / and -",
            ));
        }
        Ok(Self(value.to_string()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl TryFrom<String> for NoteKey {
    type Error = ValidationError;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        NoteKey::new(&value)
    }
}

/// One step of the Lead's plan; `agent` is a slug or "self".
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct PlanStep {
    pub agent: String,
    pub goal: String,
}

/// What a call would do, for the card and custody.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct Action {
    pub verb: String,
    pub target: Target,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
#[ts(export)]
pub enum Target {
    File { path: String },
    Recipient { channel: String, address: String },
    Message { id: String },
    Host { url: String, host: String },
    Note { scope: MemoryScope, key: NoteKey },
    Query { text: String },
    Agent { slug: Slug },
    Plan { steps: Vec<PlanStep> },
}
